import { afterAll, beforeAll, describe, expect, test } from 'bun:test';
import { createHash } from 'node:crypto';
import type { Actor, UserId } from '@crewstation/contracts';
import type { Transaction } from '@crewstation/persistence';
import { generateSecretKey } from '@crewstation/secretbox';
import { createTestDatabase, testDatabaseAvailable, type TestDatabase } from '@crewstation/testkit';
import { dataControlMigrations } from '../../data-control/wiring';
import { objectEndpointStore } from '../../data-control/adapters/persistence/objectEndpoints';
import { secretboxCipher } from '../../data-control/adapters/crypto/secretboxCipher';
import { probeObjectBucket } from '../../data-control/adapters/http/objectProbe';
import { s3ObjectPlane } from '../../data-control/adapters/http/s3Objects';
import { objectEndpointUseCases } from '../../data-control/application/objectEndpoints';
import { prepareObjectCredentialRotation } from '../../data-control/application/objectCredentialRotation';
import { garageAvailable, startGarage } from '../../data-control/tests/garageFixture';
import { dataMigrations } from '../wiring';
import { objectCredentialRotations } from '../adapters/persistence/objectRotation';
import { objectAdministration } from '../application/objectAdministration';
import type { ObjectBackendPlane } from '../ports/objectStorage';
import { objectArchiveFixture } from './objectArchiveFixture';
import { objectId } from './objectFixtures';

const available = await testDatabaseAvailable() && garageAvailable;
describe.skipIf(!available)('real Garage credential rotation with encrypted PostgreSQL metadata', () => {
  let tdb: TestDatabase, garage: Awaited<ReturnType<typeof startGarage>>;
  beforeAll(async () => { tdb = await createTestDatabase([dataControlMigrations, dataMigrations]); garage = await startGarage(); }, 90_000);
  afterAll(async () => { await garage?.dispose(); await tdb?.drop(); }, 30_000);
  test('old bytes survive switching to a separately authorized key and revoking the old one', async () => {
    const f = await objectArchiveFixture(tdb.db), store = objectEndpointStore(tdb.db), cipher = secretboxCipher(generateSecretKey());
    const endpoints = objectEndpointUseCases({ store, cipher, probe: probeObjectBucket });
    await endpoints.configure(f.backend.id, 1, 1, garage.config);
    const original = { ...garage.config }, rotated = await garage.issueCredentials();
    const prepareRotation = prepareObjectCredentialRotation({ store, cipher, probe: probeObjectBucket, within: (tx) => objectEndpointStore(tx as Transaction) });
    const plane = { ...s3ObjectPlane({ endpoint: endpoints.resolve }), prepareRotation } as ObjectBackendPlane;
    const api = objectAdministration({ ...f, plane, rotations: objectCredentialRotations(tdb.db), authorizer: { authorize: async () => {} } });
    const actor: Actor = { userId: objectId() as UserId, isAdmin: true };
    const object = { backendId: f.backend.id, placementRevision: 1, key: `spaces/${f.space.id}/attempts/${objectId()}` };
    const bytes = new TextEncoder().encode('轮换前保存的不可变内容'), sha256 = createHash('sha256').update(bytes).digest('hex');
    const signal = AbortSignal.timeout(30_000);
    await plane.put(object, { body: new Blob([bytes]).stream(), size: bytes.length, sha256, signal });
    const input = { requestKey: objectId(), expectedRevision: 1, ...rotated, reason: '隔离后端轮换验收', confirmation: 'rotate' as const };
    expect(await api.rotateCredential(actor, f.backend.id, input)).toMatchObject({ credentialRevision: 2, placementRevision: 1 });
    await garage.revokeCredentials(original.accessKeyId);
    await expect(probeObjectBucket(original, signal)).rejects.toMatchObject({ kind: 'unavailable' });
    expect(await plane.verify(object, signal)).toEqual({ size: bytes.length, sha256 });
    expect((await api.rotateCredential(actor, f.backend.id, input)).credentialRevision).toBe(2);
    const second = { ...object, key: `${object.key}-new` };
    await plane.put(second, { body: new Blob([bytes]).stream(), size: bytes.length, sha256, signal });
    expect(await plane.verify(second, signal)).toEqual({ size: bytes.length, sha256 });
    await plane.remove(object, signal); await plane.remove(second, signal);
    await expect(plane.get(object, { signal })).rejects.toMatchObject({ kind: 'not_found' });
    expect((await endpoints.resolve(object)).monitoring).toEqual(original.monitoring);
  }, 60_000);
});
